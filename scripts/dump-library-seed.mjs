/**
 * Dump library reading (series/days/sections) from Supabase into
 * content/*.json and supabase seed SQL files.
 *
 * Usage: node scripts/dump-library-seed.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { createHash } from "node:crypto";
import { readFileSync, existsSync, writeFileSync, mkdirSync } from "fs";
import { resolve } from "path";

function loadEnv(file) {
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadEnv(resolve(process.cwd(), ".env.local"));
loadEnv(resolve(process.cwd(), ".env"));

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error("Need NEXT_PUBLIC_SUPABASE_URL and SERVICE_ROLE_KEY");
  process.exit(1);
}

const SERIES_SLUG = "devi-navaratrula-jnanam";
const SERIES_NAME = "Devi Navaratrula Jnanam";
const supabase = createClient(url, key, { auth: { persistSession: false } });

function dollar(tag, value) {
  if (String(value).includes(`$${tag}$`)) {
    throw new Error(`dollar tag collision: ${tag}`);
  }
  return `$${tag}$${value}$${tag}$`;
}

function asParagraphs(content) {
  if (Array.isArray(content)) return content.map((p) => String(p));
  if (typeof content === "string") {
    try {
      const parsed = JSON.parse(content);
      if (Array.isArray(parsed)) return parsed.map((p) => String(p));
    } catch {
      /* plain string */
    }
    return [content];
  }
  return [];
}

const { data: series, error: seriesError } = await supabase
  .from("series")
  .select("id, slug, name")
  .eq("slug", SERIES_SLUG)
  .maybeSingle();
if (seriesError || !series) {
  console.error(seriesError?.message || "Series not found");
  process.exit(1);
}

const { data: dayRows, error: daysError } = await supabase
  .from("days")
  .select("id, day_number, title, subtitle, language, published, cover_url, youtube_id")
  .eq("series_id", series.id)
  .order("day_number")
  .order("language");
if (daysError) {
  console.error(daysError.message);
  process.exit(1);
}

console.log(`Found ${dayRows?.length ?? 0} day row(s) for ${SERIES_SLUG}`);

const days = [];
for (const row of dayRows ?? []) {
  const { data: sections, error: secError } = await supabase
    .from("sections")
    .select("id, section_order, title, content, minutes, start_sec")
    .eq("day_id", row.id)
    .order("section_order");
  if (secError) {
    console.error(`day ${row.day_number} ${row.language}:`, secError.message);
    process.exit(1);
  }
  days.push({
    id: row.id,
    dayNumber: row.day_number,
    language: row.language,
    series: SERIES_SLUG,
    title: row.title,
    subtitle: row.subtitle ?? "",
    coverUrl: row.cover_url,
    youtubeId: row.youtube_id,
    published: row.published !== false,
    sections: (sections ?? []).map((section) => ({
      id: section.id,
      sectionOrder: section.section_order,
      title: section.title,
      content: asParagraphs(section.content),
      minutes: section.minutes,
      startSec: section.start_sec,
    })),
  });
  console.log(
    `  day ${row.day_number} (${row.language}): ${row.title} · ${sections?.length ?? 0} sections`,
  );
}

const contentDir = resolve(process.cwd(), "content");
mkdirSync(contentDir, { recursive: true });

for (const day of days) {
  const payload = {
    dayNumber: day.dayNumber,
    language: day.language,
    series: day.series,
    title: day.title,
    subtitle: day.subtitle,
    sections: day.sections.map(({ id, sectionOrder, title, content, minutes }) => ({
      id,
      sectionOrder,
      title,
      content,
      minutes,
    })),
  };
  const filename = `day-${String(day.dayNumber).padStart(2, "0")}-${day.language}.json`;
  writeFileSync(resolve(contentDir, filename), `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`wrote content/${filename}`);
}

function emitDaySql(dayList, label) {
  const sql = [];
  sql.push(`-- Generated by scripts/dump-library-seed.mjs from live DB`);
  sql.push(`-- ${label} for ${SERIES_NAME} (${SERIES_SLUG}).`);
  sql.push("");
  sql.push(`insert into public.series (slug, name)`);
  sql.push(`values ('${SERIES_SLUG}', ${dollar("seriesname", SERIES_NAME)})`);
  sql.push(`on conflict (slug) do update set name = excluded.name;`);
  sql.push("");

  for (const day of dayList) {
    const tag = `d${day.dayNumber}${day.language}`;
    sql.push(`insert into public.days (series_id, day_number, title, subtitle, language, published)`);
    sql.push(
      `select s.id, ${day.dayNumber}, ${dollar(`${tag}title`, day.title)}, ${dollar(`${tag}sub`, day.subtitle)}, '${day.language}', ${day.published}`,
    );
    sql.push(`from public.series s`);
    sql.push(`where s.slug = '${SERIES_SLUG}'`);
    sql.push(`on conflict (series_id, day_number, language) do update`);
    sql.push(`set title = excluded.title, subtitle = excluded.subtitle, published = excluded.published;`);
    sql.push("");

    sql.push(`delete from public.sections sec`);
    sql.push(`using public.days d`);
    sql.push(`join public.series s on s.id = d.series_id`);
    sql.push(`where sec.day_id = d.id`);
    sql.push(`  and s.slug = '${SERIES_SLUG}'`);
    sql.push(`  and d.day_number = ${day.dayNumber}`);
    sql.push(`  and d.language = '${day.language}'`);
    sql.push(`  and sec.section_order > ${day.sections.length};`);
    sql.push("");

    for (const section of day.sections) {
      const stag = `${tag}s${section.sectionOrder}`;
      const id =
        section.id ||
        (() => {
          const hash = createHash("sha256")
            .update(`reading-${SERIES_SLUG}-day-${day.dayNumber}-${day.language}-${section.sectionOrder}`)
            .digest("hex");
          return [
            hash.slice(0, 8),
            hash.slice(8, 12),
            `4${hash.slice(13, 16)}`,
            `a${hash.slice(17, 20)}`,
            hash.slice(20, 32),
          ].join("-");
        })();
      sql.push(`insert into public.sections (id, day_id, section_order, title, content, minutes)`);
      sql.push(`select`);
      sql.push(`  '${id}'::uuid,`);
      sql.push(`  d.id,`);
      sql.push(`  ${section.sectionOrder},`);
      sql.push(`  ${dollar(`${stag}title`, section.title)},`);
      sql.push(`  ${dollar(`${stag}json`, JSON.stringify(section.content))}::jsonb,`);
      sql.push(`  ${section.minutes ?? "null"}`);
      sql.push(`from public.days d`);
      sql.push(`join public.series s on s.id = d.series_id`);
      sql.push(
        `where s.slug = '${SERIES_SLUG}' and d.day_number = ${day.dayNumber} and d.language = '${day.language}'`,
      );
      sql.push(`on conflict (day_id, section_order) do update`);
      sql.push(
        `set id = excluded.id, title = excluded.title, content = excluded.content, minutes = excluded.minutes, updated_at = now();`,
      );
      sql.push("");
    }
  }
  return sql.join("\n");
}

const enDays = days.filter((d) => d.language === "en").sort((a, b) => a.dayNumber - b.dayNumber);
const teDays = days.filter((d) => d.language === "te").sort((a, b) => a.dayNumber - b.dayNumber);
const teExcept8 = teDays.filter((d) => d.dayNumber !== 8);
const day8 = days.filter((d) => d.dayNumber === 8);

const seedDir = resolve(process.cwd(), "supabase");
writeFileSync(resolve(seedDir, "seed-devi-en.sql"), emitDaySql(enDays, "English days"));
console.log(`wrote supabase/seed-devi-en.sql (${enDays.length} days)`);

writeFileSync(
  resolve(seedDir, "seed-devi-te.sql"),
  emitDaySql(teExcept8, "Telugu days (excl. day 8 — see seed.sql)"),
);
console.log(`wrote supabase/seed-devi-te.sql (${teExcept8.length} days)`);

if (day8.length) {
  writeFileSync(
    resolve(seedDir, "seed.sql"),
    [
      "-- Day 8 Telugu + English under Devi Navaratrula Jnanam.",
      "-- Regenerated by scripts/dump-library-seed.mjs from live DB.",
      "-- Other Telugu days: supabase/seed-devi-te.sql",
      "-- English days: supabase/seed-devi-en.sql",
      "",
      emitDaySql(day8, "Day 8 only"),
    ].join("\n"),
  );
  console.log(`wrote supabase/seed.sql (${day8.length} day-8 row(s))`);
}

console.log("Done.");
