/**
 * Pulls chapter JSON out of the static Day 8 reader HTML files
 * and writes app content plus a Supabase seed.
 *
 * Usage: node scripts/extract-reader-html.mjs
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readerDir = path.join(root, "9-Day-Devi-Navaratri-Dr-Newton");

const sources = [
  {
    file: "day-08.html",
    language: "te",
    title: "జ్ఞానోదయం",
    subtitle: "దేవీ నవరాత్రులు · Day 8",
  },
  {
    file: "day-08-en.html",
    language: "en",
    title: "Jnanodayam",
    subtitle: "Devi Navaratri · Day 8 (English)",
  },
];

function sectionId(language, sectionOrder) {
  const hash = createHash("sha256")
    .update(`qlu-day-8-${language}-${sectionOrder}`)
    .digest("hex");
  return [
    hash.slice(0, 8),
    hash.slice(8, 12),
    `4${hash.slice(13, 16)}`,
    `a${hash.slice(17, 20)}`,
    hash.slice(20, 32),
  ].join("-");
}

function extractChapters(html) {
  const marker = "const chapters=";
  const start = html.indexOf(marker);
  if (start < 0) throw new Error("chapters array not found");
  const jsonStart = start + marker.length;
  const navAt = html.indexOf("const nav=", jsonStart);
  if (navAt < 0) throw new Error("nav marker not found");
  const end = html.lastIndexOf("];", navAt);
  if (end < 0) throw new Error("end of chapters array not found");
  return JSON.parse(html.slice(jsonStart, end + 1));
}

function dollar(tag, value) {
  if (String(value).includes(`$${tag}$`)) {
    throw new Error(`dollar tag collision: ${tag}`);
  }
  return `$${tag}$${value}$${tag}$`;
}

const days = sources.map((source) => {
  const html = fs.readFileSync(path.join(readerDir, source.file), "utf8");
  const chapters = extractChapters(html);
  return {
    dayNumber: 8,
    language: source.language,
    title: source.title,
    subtitle: source.subtitle,
    sections: chapters.map((chapter, index) => ({
      id: sectionId(source.language, index + 1),
      sectionOrder: index + 1,
      title: chapter.title,
      content: chapter.paras,
      minutes: chapter.minutes ?? null,
    })),
  };
});

const contentDir = path.join(root, "content");
fs.mkdirSync(contentDir, { recursive: true });
for (const day of days) {
  const filename = `day-0${day.dayNumber}-${day.language}.json`;
  fs.writeFileSync(path.join(contentDir, filename), JSON.stringify(day, null, 2) + "\n");
  console.log(`wrote content/${filename} (${day.sections.length} sections)`);
}

const sql = [];
sql.push("-- Generated by scripts/extract-reader-html.mjs");
sql.push("-- Day 8 Telugu + English. Requires unique (day_number, language).");
sql.push("");

for (const day of days) {
  const tag = `day8${day.language}`;
  sql.push(`insert into public.days (day_number, title, subtitle, language, published)`);
  sql.push(
    `values (8, ${dollar(`${tag}title`, day.title)}, ${dollar(`${tag}sub`, day.subtitle)}, '${day.language}', true)`,
  );
  sql.push(`on conflict (day_number, language) do update`);
  sql.push(`set title = excluded.title, subtitle = excluded.subtitle, published = excluded.published;`);
  sql.push("");

  day.sections.forEach((section) => {
    const stag = `${tag}s${section.sectionOrder}`;
    sql.push(`insert into public.sections (id, day_id, section_order, title, content, minutes)`);
    sql.push(`select`);
    sql.push(`  '${section.id}'::uuid,`);
    sql.push(`  d.id,`);
    sql.push(`  ${section.sectionOrder},`);
    sql.push(`  ${dollar(`${stag}title`, section.title)},`);
    sql.push(`  ${dollar(`${stag}json`, JSON.stringify(section.content))}::jsonb,`);
    sql.push(`  ${section.minutes ?? "null"}`);
    sql.push(`from public.days d`);
    sql.push(`where d.day_number = 8 and d.language = '${day.language}'`);
    sql.push(`on conflict (day_id, section_order) do update`);
    sql.push(`set title = excluded.title, content = excluded.content, minutes = excluded.minutes, updated_at = now();`);
    sql.push("");
  });
}

const seedDir = path.join(root, "supabase");
fs.mkdirSync(seedDir, { recursive: true });
fs.writeFileSync(path.join(seedDir, "seed.sql"), sql.join("\n"));
console.log("wrote supabase/seed.sql");
